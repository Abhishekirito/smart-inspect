export const EXTRACTION_SCHEMA = {
  is_same_commodity: 'boolean (true if all provided image text belongs to the SAME packaged product, false if images describe 2 DIFFERENT products)',
  commodity_mismatch_reason: 'string|null (if false, explain the mismatch e.g. Image 1 is Parle-G but Image 2 is Tata Salt)',
  product_name: 'string|null',
  common_generic_name: 'string|null',
  manufacturer_packer_importer: 'string|null (full name + address as printed)',
  has_full_address: 'boolean (true only if a city/state or PIN code is present)',
  net_quantity_raw: 'string|null (exactly as printed, e.g. "Net Wt. 500 g")',
  net_quantity_value: 'number|null (numeric part only, e.g. 500)',
  net_quantity_unit: 'one of g,kg,mg,ml,l,cm,m,sqcm,sqm,N,U or null',
  mrp_raw: 'string|null (full MRP line as printed)',
  mrp_value: 'number|null',
  mrp_tax_inclusive: 'boolean (true if it says inclusive of all taxes)',
  mfg_date_raw: 'string|null (month/year of manufacture, packing or import)',
  consumer_care_raw: 'string|null (customer care / complaint contact)',
  country_of_origin: 'string|null',
  is_imported: 'boolean',
  dimensions_raw: 'string|null (size/dimensions if printed)',
  commodity_category: 'string|null (e.g. biscuits, tea, soap, bedsheet, cement)',
  commodity_type: 'string|null (food | cosmetic | agricultural_produce | general)',
  buyer_type: 'string (retail | industrial_consumer | institutional_consumer)',
}

const PROMPT = `You are a data-extraction engine for Indian Legal Metrology label compliance.
From the packaged-commodity label text below, extract EXACTLY this JSON object and NOTHING else.
Do not judge compliance. Only transcribe what is printed. Use null when a field is absent.
Schema (value = description of what to put):
${JSON.stringify(EXTRACTION_SCHEMA, null, 2)}
Return only minified valid JSON.`

export function fileToDataURL(file) {
  return new Promise((resolve, reject) => {
    const r = new FileReader()
    r.onload = () => resolve(r.result)
    r.onerror = reject
    r.readAsDataURL(file)
  })
}

export function stripToJSON(text) {
  if (!text) return null
  // 1. Strip reasoning / think tags generated by models like DeepSeek / Qwen
  let clean = text.replace(/<think>[\s\S]*?<\/think>/gi, '').trim()

  // 2. Extract content from markdown code fences if present
  const jsonBlockMatch = clean.match(/```(?:json)?\s*([\s\S]*?)\s*```/i)
  if (jsonBlockMatch && jsonBlockMatch[1]) {
    clean = jsonBlockMatch[1].trim()
  }

  // 3. Find outermost JSON object braces
  const s = clean.indexOf('{')
  const e = clean.lastIndexOf('}')
  if (s === -1 || e === -1 || e < s) return null

  try {
    return JSON.parse(clean.slice(s, e + 1))
  } catch {
    return null
  }
}

export function getValidGoogleKey(k1, k2) {
  const isValid = (k) => k && typeof k === 'string' && k.trim().length > 15
  if (isValid(k1)) return k1.trim()
  if (isValid(k2)) return k2.trim()
  return ''
}

